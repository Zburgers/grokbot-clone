import { test, after } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const dir = mkdtempSync(join(tmpdir(), 'grokbot-memory-'));
Object.assign(process.env, { DB_PATH: join(dir, 'test.db'), COMPOSIO_API_KEY: 'test', DESKTOP_TOKEN: 'test', SESSION_SECRET: 'test', LLM_API_KEY: 'test' });
const { db } = await import('../server/src/db.ts');
db.prepare('INSERT INTO users(id,email,name,created_at) VALUES (?,?,?,0)').run('u', 'test@test.invalid', 'Owner');
for (const id of ['a', 'b']) db.prepare('INSERT INTO bots(id,user_id,name,created_at,updated_at) VALUES (?,?,?,0,0)').run(id, 'u', id);
const memories = await import('../server/src/bot-memory.ts').catch(() => ({}));
const { memoriesForPrompt } = await import('../server/src/agent/memory.ts');
test('corrections supersede facts atomically and exclude stale facts from prompt and recall', () => {
  assert.equal(typeof memories.saveMemory, 'function');
  const saved = memories.saveMemory('a', 'Native bots cannot be created.');
  assert.equal(memories.saveMemory('a', 'Native bots cannot be created.').id, saved.id);
  assert.throws(() => memories.correctMemory('b', saved.id, 'Incorrect cross-bot rewrite', 'test'), /not found/i);
  const corrected = memories.correctMemory('a', saved.id, 'Native bots can be created using create_bot.', 'Verified installed tool registry');
  assert.equal(memories.activeMemories('a').length, 1);
  assert.equal(memories.activeMemories('a')[0].id, corrected.id);
  assert.ok(!JSON.stringify(memoriesForPrompt('a')).includes('cannot'));
  assert.ok(!JSON.stringify(memories.recallMemory('a', 'native')).includes('cannot'));
  assert.equal(db.prepare('SELECT status FROM memories WHERE id=?').get(saved.id).status, 'superseded');
  assert.equal(db.prepare('SELECT count(*) n FROM memory_events WHERE memory_id=?').get(saved.id).n, 1);
});
test('forgetting is scoped and recoverable; expired observations stay out of prompt and recall', () => {
  assert.equal(typeof memories.forgetMemory, 'function');
  const saved = memories.saveMemory('a', 'Prefers direct pushes.');
  assert.equal(memories.forgetMemory('b', saved.id, 'wrong bot'), false);
  assert.equal(memories.forgetMemory('a', saved.id, 'Owner asked to forget'), true);
  assert.equal(db.prepare('SELECT status FROM memories WHERE id=?').get(saved.id).status, 'forgotten');
  assert.ok(!JSON.stringify(memories.activeMemories('a')).includes('Prefers direct'));
  const observed = memories.saveMemory('a', 'The device is offline.', { kind: 'observation', expiresAt: Date.now() - 1 });
  assert.ok(!memories.activeMemories('a').some(m => m.id === observed.id));
  assert.ok(!JSON.stringify(memoriesForPrompt('a')).includes('offline'));
  assert.deepEqual(memories.recallMemory('a', 'offline'), []);
  assert.throws(() => memories.saveMemory('a', ''), /text/i);
});
after(() => { db.close(); rmSync(dir, { recursive: true, force: true }); });
